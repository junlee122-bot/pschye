const episodeDrafts = [petalBeforeBloom, erasedNames, sixBanners, secondGreatWar, lamiOrigin];

export const grandStoryEpisodes: GrandStoryEpisode[] = episodeDrafts.flatMap((episodes) =>
  episodes.map((entry, index) => ({ ...entry, order: index + 1 })),
);

let globalSceneOrder = 0;

export const grandStoryScenes: GrandStoryScene[] = grandStoryEpisodes.flatMap((entry) =>
  entry.beats.map(([title, mode, summary], index) => {
    globalSceneOrder += 1;
    const localOrder = index + 1;
    const isDecision = localOrder === 5;
    const nextBeat = entry.beats[index + 1];

    return {
      id: `${entry.sagaId}-${entry.id}-${String(localOrder).padStart(2, '0')}`,
      globalOrder: globalSceneOrder,
      episodeId: entry.id,
      episodeOrder: entry.order,
      localOrder,
      sagaId: entry.sagaId,
      chapter: entry.chapter,
      episodeTitle: entry.title,
      title,
      phase: scenePhases[index],
      mode,
      time: entry.time,
      location: entry.location,
      viewpoint: entry.viewpoint,
      cast: entry.cast,
      summary,
      canonStatus: entry.canonStatus,
      canonNotice: entry.canonNotice,
      playerGoal: modeGoals[mode],
      choicePrompt: isDecision ? entry.choicePrompt : undefined,
      choices: isDecision
        ? [
            { path: 'compassion' as const, line: entry.choices[0] },
            { path: 'insight' as const, line: entry.choices[1] },
            { path: 'resolve' as const, line: entry.choices[2] },
          ]
        : undefined,
      continuity: nextBeat ? `다음 장면: ${nextBeat[0]}` : entry.cliffhanger,
    };
  }),
);

