import assert from 'node:assert/strict';
import { create, origin, clean } from './native-boundary-common.mjs';
const s = await create('mobile');
try {
  await s.page.goto(origin + '/?section=campaign');
  await s.page.locator('.village-interact-prompt').waitFor();
  s.record('initial', { xy: await s.xy(), profile: await s.profile(), metrics: await s.metrics(), ax: await s.page.locator('body').ariaSnapshot() });
  await s.snap('village-390');
  const right = s.page.getByRole('button', { name: '오른쪽으로 이동', exact: true });
  const before = await s.xy();
  const box = await right.boundingBox();
  await s.page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await s.page.mouse.down();
  await s.page.waitForTimeout(330);
  await s.page.mouse.move(200, 500);
  await s.page.mouse.up();
  await s.page.waitForTimeout(150);
  const released = await s.xy();
  await s.page.waitForTimeout(850);
  const settled = await s.xy();
  assert.ok(released.x > before.x);
  assert.deepEqual(settled, released);
  s.record('mouse-hold-release-outside', { before, released, settled, pointerType: 'mouse', durationMs: 330, saved: (await s.profile()).world.village });
  // Return through actual one-step keyboard activation, without assigning position.
  while ((await s.xy()).x > 814.1) await s.page.getByRole('button', { name: '왼쪽으로 이동', exact: true }).press('Enter');
  await s.page.locator('.village-interact-prompt').waitFor();
  const down = s.page.getByRole('button', { name: '아래로 이동', exact: true });
  const downBox = await down.boundingBox();
  const cancelBefore = await s.xy();
  await s.page.mouse.move(downBox.x + downBox.width / 2, downBox.y + downBox.height / 2);
  await s.page.mouse.down();
  await s.page.waitForTimeout(210);
  await down.dispatchEvent('pointercancel', { pointerId: 1, pointerType: 'mouse', bubbles: true });
  const cancelled = await s.xy();
  await s.page.waitForTimeout(850);
  const afterCancel = await s.xy();
  await s.page.mouse.up();
  assert.deepEqual(afterCancel, cancelled);
  s.record('synthetic-cancel-handler', { cancelBefore, cancelled, afterCancel, method: 'actual mouse hold followed by explicitly synthetic pointercancel; not an OS touch cancellation' });
  while ((await s.xy()).y > 382.1) await s.page.getByRole('button', { name: '위로 이동', exact: true }).press('Enter');
  await s.page.locator('.village-interact-prompt').waitFor();
  await s.page.locator('.village-interact-prompt').tap();
  await s.page.getByRole('dialog').waitFor();
  const dialogueBefore = await s.xy();
  await s.page.keyboard.down('ArrowRight');
  await s.page.waitForTimeout(350);
  await s.page.keyboard.up('ArrowRight');
  await s.page.getByRole('button', { name: '아래로 이동', exact: true }).tap();
  await s.page.waitForTimeout(850);
  const dialogueAfter = await s.xy();
  assert.deepEqual(dialogueAfter, dialogueBefore);
  s.record('dialogue-blocks-input', { dialogueBefore, dialogueAfter, actualInputs: ['trusted touchscreen tap open dialogue', 'keyboard ArrowRight held 350ms', 'trusted touchscreen tap down'], dialog: await s.page.getByRole('dialog').innerText() });
  await s.page.setViewportSize({ width: 320, height: 844 });
  s.record('dialogue-320', { metrics: await s.metrics() }); await s.snap('dialogue-320');
  await s.page.keyboard.press('Escape');
  const finalXY = await s.xy();
  await s.page.getByRole('button', { name: '타이틀', exact: true }).click();
  await s.page.locator('.title-save-slots').waitFor();
  const saved = clean(await s.profile());
  s.record('title-320', { metrics: await s.metrics(), saved }); await s.snap('title-320');
  await s.page.reload();
  await s.page.locator('.title-save-slots').waitFor();
  await s.page.getByRole('button', { name: /여정 계속/ }).click();
  await s.page.locator('.village-engine canvas').waitFor();
  await s.page.waitForTimeout(500);
  const resumed = await s.xy();
  assert.deepEqual(resumed, finalXY);
  assert.deepEqual(clean(await s.profile()), saved);
  s.record('release-title-reload-resume', { finalXY, resumed, wholeProfileEqual: true, metrics: await s.metrics() });
  await s.snap('village-320');
} catch (error) { await s.finish(error); process.exitCode = 1; }
finally { if (s.browser.isConnected()) await s.finish(); }
