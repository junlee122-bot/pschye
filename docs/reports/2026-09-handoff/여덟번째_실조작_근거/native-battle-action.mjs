import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('<LOCAL_USER_HOME>/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const dir = path.dirname(fileURLToPath(import.meta.url));
const storage = path.join(dir, 'native-first-mode-select-storage.json');
const origin = JSON.parse(fs.readFileSync(storage, 'utf8')).origins[0].origin;
const log = { scope: 'Actual action movement/orders/pause/reload, enemy-caused defeat, retry and mode switch', origin, events: [], checks: {}, errors: [] };
const record = (label, data = {}) => { log.events.push({ at: new Date().toISOString(), label, ...data }); console.log(JSON.stringify({ label, ...data })); };
const write = (name, data) => fs.writeFileSync(path.join(dir, name), JSON.stringify(data, null, 2));
let browser;
try {
  browser = await chromium.launch({ executablePath: '<LOCAL_PROGRAM_FILES> (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--disk-cache-size=1048576'] });
  log.browser = browser.version();
  const context = await browser.newContext({ storageState: storage, viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', e => log.errors.push({ kind: 'pageerror', message: e.message }));
  page.on('console', m => { if (m.type() === 'error') log.errors.push({ kind: 'console', message: m.text() }); });
  const profile = () => page.evaluate(() => JSON.parse(localStorage.getItem('raonjena-campaign-v10-slot-1')));
  const shot = name => page.screenshot({ path: path.join(dir, `native-battle-${name}.png`) });
  const summary = p => ({ id: p.battleAttempt?.id, mode: p.battleAttempt?.mode, outcome: p.battleAttempt?.battle.outcome, round: p.battleAttempt?.battle.round, elapsed: p.battleAttempt?.action?.elapsed, hp: p.battleAttempt?.battle.heroes.find(h => h.id === 'raon').hp, objectiveHp: p.battleAttempt?.battle.carriageHp, player: p.battleAttempt?.action?.player, orders: p.battleAttempt?.action?.orders });
  await page.goto(`${origin}/?section=campaign`, { waitUntil: 'networkidle' });
  await page.locator('.battle-resume-primary').click();
  await page.locator('.combat-mode-card.action').click();
  await page.locator('.action-onboarding-actions .primary').waitFor();
  const initial = await profile();
  assert.equal(await page.locator('.action-companion-orders button').count(), 5);
  await page.setViewportSize({ width: 390, height: 844 });
  await shot('action-guide');
  await page.locator('.action-onboarding-actions .primary').click();
  await page.waitForFunction(() => Boolean(JSON.parse(localStorage.getItem('raonjena-campaign-v10-slot-1')).battleAttempt?.action));
  const started = await profile();
  record('Actual action runtime started', summary(started));
  await page.keyboard.down('d'); await page.waitForTimeout(350); await page.keyboard.up('d');
  await page.locator('.action-companion-orders button').filter({ hasText: '크리스' }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('raonjena-campaign-v10-slot-1')).battleAttempt?.action?.orders.chris > 0);
  const mobileBounds = await page.locator('.action-companion-orders button').evaluateAll(elements => elements.map(element => { const r = element.getBoundingClientRect(); return { text: element.textContent, x: r.x, y: r.y, width: r.width, height: r.height }; }));
  const mobileWidth = await page.evaluate(() => ({ viewport: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
  assert(mobileBounds.every(r => r.x >= 0 && r.x + r.width <= 391));
  assert(mobileWidth.scrollWidth <= mobileWidth.viewport);
  log.checks.mobile390CompanionActualClick = { buttons: mobileBounds, ...mobileWidth, cooldown: (await profile()).battleAttempt.action.orders.chris };
  await shot('action-mobile-companion');
  await page.locator('.action-command-bar button').filter({ hasText: '흐름 읽기' }).click();
  await page.locator('.action-command-bar button').filter({ hasText: '간격 이탈' }).click();
  await page.locator('.action-guide-strip button').click();
  await page.locator('.action-onboarding').waitFor();
  const paused = await profile();
  assert(paused.battleAttempt.action.player.x > started.battleAttempt.action.player.x);
  assert(paused.battleAttempt.action.orders.chris > 0);
  assert(paused.battleAttempt.battle.enemies.find(e => e.id === 'sky-sniper').revealed);
  const pausedElapsed = paused.battleAttempt.action.elapsed;
  await page.waitForTimeout(700);
  assert.equal((await profile()).battleAttempt.action.elapsed, pausedElapsed);
  log.checks.realMovementOrderParryDodgeInputs = true;
  log.checks.pauseStopsSimulation = true;
  write('native-battle-action-paused-profile.json', paused);
  await shot('action-paused');
  // The pause dialog covers the header; resume through its real button before exiting.
  await page.locator('.action-onboarding-actions .primary').click();
  await page.getByRole('button', { name: '저장하고 나가기', exact: true }).click();
  await page.locator('.battle-resume-primary').waitFor();
  const exited = await profile();
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.battle-resume-primary').click();
  await page.locator('.action-onboarding').waitFor();
  const restored = await profile();
  assert.equal(restored.battleAttempt.id, exited.battleAttempt.id);
  assert.deepEqual(restored.battleAttempt.action, exited.battleAttempt.action);
  await page.waitForTimeout(600);
  assert.deepEqual((await profile()).battleAttempt.action, exited.battleAttempt.action);
  log.checks.actionReloadExactAndGuidePaused = true;
  record('Action movement and remaining timers restored exactly', summary(restored));
  await page.locator('.action-onboarding-actions .primary').click();
  // Actual wall time and native enemy simulation, with no combat input or clock jumps.
  for (let elapsed = 0; elapsed < 170; elapsed += 5) {
    await page.waitForTimeout(5000);
    const p = await profile();
    record('Enemy-only live interval', summary(p));
    if (p.battleAttempt.battle.outcome !== 'active') break;
  }
  await page.locator('.action-outcome article.defeat').waitFor({ timeout: 5000 });
  const lost = await profile();
  assert.equal(lost.battleAttempt.battle.outcome, 'defeat');
  assert.equal(lost.battleAttempt.settled, false);
  for (const key of ['day', 'supplies', 'intel', 'relics', 'renown', 'heroProgress', 'completedMissions', 'unlockedRecords']) assert.deepEqual(lost[key], initial[key]);
  assert(lost.battleAttempt.battle.carriageHp < initial.battleAttempt.battle.carriageHp || lost.battleAttempt.battle.heroes.find(h => h.id === 'raon').hp < initial.battleAttempt.battle.heroes.find(h => h.id === 'raon').hp);
  log.checks.actualEnemyDefeatNoRewards = true;
  write('native-battle-action-defeat-profile.json', lost);
  await shot('action-defeat');
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.battle-resume-primary').click();
  await page.locator('.action-outcome article.defeat').waitFor();
  assert.equal((await profile()).battleAttempt.id, lost.battleAttempt.id);
  await page.locator('.action-outcome').getByRole('button', { name: '다시 도전', exact: true }).click();
  await page.waitForFunction(id => JSON.parse(localStorage.getItem('raonjena-campaign-v10-slot-1')).battleAttempt?.id !== id, lost.battleAttempt.id);
  // The newly retried action runtime may begin immediately because the guide was already seen.
  await page.locator('.action-guide-strip button').waitFor();
  await page.locator('.action-guide-strip button').click();
  const retried = await profile();
  assert.equal(retried.battleAttempt.battle.outcome, 'active');
  assert.deepEqual(retried.battleAttempt.heroes, initial.battleAttempt.heroes);
  log.checks.defeatReloadAndRetryFrozenDeployment = true;
  record('Actual defeat restored; retry creates fresh ID', summary(retried));
  // Cancel a mode switch first, then accept it using the real confirmation dialog.
  page.once('dialog', dialog => dialog.dismiss());
  await page.locator('.action-onboarding-actions button').filter({ hasText: '전술 모드로 시작' }).click();
  assert.equal((await profile()).battleAttempt.id, retried.battleAttempt.id);
  page.once('dialog', dialog => dialog.accept());
  await page.locator('.action-onboarding-actions button').filter({ hasText: '전술 모드로 시작' }).click();
  await page.locator('.battle-page').waitFor();
  const tactical = await profile();
  assert.notEqual(tactical.battleAttempt.id, retried.battleAttempt.id);
  assert.equal(tactical.battleAttempt.mode, 'tactical');
  assert.equal(tactical.battleAttempt.action, undefined);
  assert.deepEqual(tactical.battleAttempt.heroes, initial.battleAttempt.heroes);
  assert.deepEqual(tactical.battleAttempt.battle, initial.battleAttempt.battle);
  log.checks.modeCancelKeepsIdAcceptResetsWithFrozenStats = true;
  write('native-battle-action-to-tactical-profile.json', tactical);
  log.status = 'passed';
} catch (error) {
  log.status = 'failed'; log.failure = { message: error.message, stack: error.stack };
  console.error(error); process.exitCode = 1;
  const page = browser?.contexts()[0]?.pages()[0];
  if (page) { try { await page.screenshot({ path: path.join(dir, 'native-battle-action-failure.png') }); write('native-battle-action-failure-profile.json', await page.evaluate(() => JSON.parse(localStorage.getItem('raonjena-campaign-v10-slot-1')))); } catch {} }
} finally { write('native-battle-action-results.json', log); if (browser) await browser.close(); }
